"""
Build the static pages in web/ from web-src/ (shared navbar, footer and head live in one place).

    python scripts/build_web.py            # write web/*.html
    python scripts/build_web.py --check    # exit 1 if web/*.html differ from what the sources produce

web-src/pages/*.html start with a small front matter block:

    ---
    title: Page title
    current: references.html     (optional: the navbar link marked aria-current="page")
    demo: true                   (optional: show the demo-mode controls in the navbar)
    ---

Placeholders (everything else is plain HTML):

    {{> name}}             include web-src/partials/name.html (own line)
    {{title}}              the page title
    {{current:file.html}}  ' aria-current="page"' when `current` is that file, otherwise nothing
    {{#demo}} ... {{/demo}} block kept only when `demo: true` (markers on their own lines)
    {{^demo}} ... {{/demo}} block kept only when demo is not set

Standard library only. Pages only publishes web/, so the generated files are committed.
"""
import argparse
import glob
import html
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
BANNER = "<!-- Generated by scripts/build_web.py from web-src/. Edit web-src/, not this file. -->\n"


def _front_matter(text):
    if not text.startswith("---\n"):
        raise ValueError("page is missing its front matter")
    end = text.index("\n---\n", 4)
    meta = {}
    for line in text[4:end].splitlines():
        key, _, value = line.partition(":")
        meta[key.strip()] = value.strip()
    return meta, text[end + len("\n---\n"):]


def _include(text, partials_dir):
    def repl(m):
        path = os.path.join(partials_dir, m.group(1) + ".html")
        if not os.path.exists(path):
            raise ValueError(f"unknown partial: {m.group(1)}")
        with open(path, encoding="utf-8") as f:
            return _include(f.read().rstrip("\n"), partials_dir)

    return re.sub(r"^\{\{> (\w+)\}\}$", repl, text, flags=re.M)


def _render(text, meta, partials_dir):
    text = _include(text, partials_dir)
    demo = meta.get("demo", "").lower() == "true"
    text = re.sub(r"^\{\{#demo\}\}\n(.*?)^\{\{/demo\}\}\n", lambda m: m.group(1) if demo else "", text, flags=re.S | re.M)
    text = re.sub(r"^\{\{\^demo\}\}\n(.*?)^\{\{/demo\}\}\n", lambda m: "" if demo else m.group(1), text, flags=re.S | re.M)
    text = re.sub(r"\{\{current:([^}]+)\}\}", lambda m: ' aria-current="page"' if meta.get("current") == m.group(1) else "", text)
    text = text.replace("{{title}}", html.escape(meta.get("title", ""), quote=False))
    left = re.findall(r"\{\{[^}]*\}\}", text)
    if left:
        raise ValueError(f"unresolved placeholders: {left}")
    return text


def build(src_dir, out_dir):
    """Write every page of src_dir/pages into out_dir and return the list of written paths."""
    os.makedirs(out_dir, exist_ok=True)
    written = []
    for page in sorted(glob.glob(os.path.join(src_dir, "pages", "*.html"))):
        with open(page, encoding="utf-8") as f:
            meta, body = _front_matter(f.read())
        page_html = _render(body, meta, os.path.join(src_dir, "partials"))
        first, rest = page_html.split("\n", 1)
        if not first.lower().startswith("<!doctype"):
            raise ValueError(f"{page} must start with a doctype (through the head partial)")
        dst = os.path.join(out_dir, os.path.basename(page))
        with open(dst, "w", encoding="utf-8", newline="\n") as f:
            f.write(first + "\n" + BANNER + rest)
        written.append(dst)
    return written


def check(src_dir, web_dir):
    """Return the names of pages in web_dir that differ from what the sources produce."""
    import tempfile

    stale = []
    with tempfile.TemporaryDirectory() as tmp:
        for path in build(src_dir, tmp):
            name = os.path.basename(path)
            target = os.path.join(web_dir, name)
            with open(path, encoding="utf-8", newline="") as f:
                new = f.read()
            old = None
            if os.path.exists(target):
                with open(target, encoding="utf-8", newline="") as f:
                    old = f.read().replace("\r\n", "\n")
            if old != new:
                stale.append(name)
    return stale


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", default=os.path.join(ROOT, "web-src"))
    ap.add_argument("--web", default=os.path.join(ROOT, "web"))
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    if args.check:
        stale = check(args.src, args.web)
        if stale:
            print("out of date:", ", ".join(stale), "(run python scripts/build_web.py)")
            return 1
        print("web/ is up to date")
        return 0
    for path in build(args.src, args.web):
        print("wrote", os.path.relpath(path, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
